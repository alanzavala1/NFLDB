"""Evaluate an official R trial against weekly totals and the credit prototype.

Run from api/: python -m experiments.evaluate_upstream_receiving_splits OUTPUT_DIR
Optional --database PATH reads existing splits strictly read-only. Source exports
and reports belong in ignored data/, never in the serving database.
"""
import argparse
import hashlib
import json
from pathlib import Path

import duckdb
import numpy as np
import pandas as pd

from experiments.receiving_credits import receiving_player_plays, receiving_splits


METRICS = ("targets", "receptions", "receiving_yards", "receiving_tds")
GIBBS = "00-0039139"
JEFFERSON = "00-0036322"


def load(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, dtype={"player_id": "string", "split_value": "string"})


def aggregate(frame: pd.DataFrame, keys: list[str]) -> pd.DataFrame:
    frame = frame.loc[frame.player_id.notna()].copy()
    if frame[keys].isna().any().any():
        raise ValueError(f"Missing comparison keys: {keys}")
    values = frame[list(METRICS)].apply(pd.to_numeric, errors="raise")
    if not np.isfinite(values.to_numpy()).all():
        raise ValueError("Missing or nonfinite receiving statistics")
    frame[list(METRICS)] = values
    return frame.groupby(keys)[list(METRICS)].sum()


def compare(left: pd.DataFrame, right: pd.DataFrame, keys: list[str]) -> dict:
    a, b = aggregate(left, keys).align(aggregate(right, keys), fill_value=0)
    delta = a - b
    result = {}
    for metric in METRICS:
        changed = delta[metric].ne(0)
        examples = pd.DataFrame({"actual": a.loc[changed, metric],
                                 "reference": b.loc[changed, metric],
                                 "delta": delta.loc[changed, metric]}).reset_index()
        result[metric] = {"mismatches": int(changed.sum()),
                          "examples": json.loads(examples.head(8).to_json(orient="records"))}
    return result


def totals(frame: pd.DataFrame) -> dict:
    return {metric: int(frame[metric].sum()) for metric in METRICS}


def evaluate(output: Path, database: Path | None) -> dict:
    run = json.loads((output / "run.json").read_text())
    report = {"scope": "REG nonconversion receiving counts; provider consistency, not independent NFL accuracy",
              "versions": {k: run[k] for k in ("nflfastR", "nflreadr")},
              "seasons": {}, "controls": {}, "failures": []}
    checks = []
    for year in run["seasons"]:
        overall = load(output / f"overall-{year}.csv")
        down = load(output / f"down-{year}.csv")
        weekly = load(output / f"weekly-{year}.csv")
        context = load(output / f"context-{year}.csv")
        credits = load(output / f"credits-{year}.csv")
        plays = receiving_player_plays(context, credits)
        prototype = plays.rename(columns={"target_credits": "targets"})
        prototype_down = receiving_splits(plays, "down").rename(columns={"target_credits": "targets"})
        comparisons = {
            "overall_vs_weekly": compare(overall, weekly, ["player_id"]),
            "overall_vs_credit_prototype": compare(overall, prototype, ["player_id"]),
            "every_down_vs_credit_prototype": compare(down, prototype_down, ["player_id", "split_value"]),
            "down_sum_vs_overall": compare(down, overall, ["player_id"]),
        }
        checks.extend((f"{year} {name}", values) for name, values in comparisons.items()
                      if name != "down_sum_vs_overall")
        identified = overall[overall.player_id.notna()]
        active = identified[list(METRICS)].ne(0).any(axis=1)
        year_report = {"active_receiving_players": int(active.sum()),
                       "totals": totals(identified), "comparisons": comparisons,
                       "credited_rows_missing_down": int((~plays.down.isin([1, 2, 3, 4])).sum()),
                       "target_completeness_verified": False}
        if year_report["credited_rows_missing_down"] == 0:
            checks.append((f"{year} down conservation", comparisons["down_sum_vs_overall"]))
        if year == 2024:
            controls = {
                "gibbs": (GIBBS, {"targets": 63, "receptions": 52, "receiving_yards": 517, "receiving_tds": 4}),
                "jefferson": (JEFFERSON, {"targets": 154, "receptions": 103, "receiving_yards": 1533, "receiving_tds": 10}),
            }
            for name, (player, expected) in controls.items():
                actual = totals(overall[overall.player_id.eq(player)])
                report["controls"][name] = {"actual": actual, "expected": expected, "passed": actual == expected}
                if actual != expected:
                    report["failures"].append(f"{name} season control")
            # Independent reviewed bucket expectations, not generated by either calculator.
            expected_down = pd.DataFrame([
                (GIBBS, "1", 23, 21, 237, 1), (GIBBS, "2", 24, 18, 168, 1),
                (GIBBS, "3", 13, 10, 74, 0), (GIBBS, "4", 3, 3, 38, 2),
                (JEFFERSON, "1", 57, 44, 546, 3), (JEFFERSON, "2", 52, 36, 615, 1),
                (JEFFERSON, "3", 41, 21, 357, 5), (JEFFERSON, "4", 4, 2, 15, 1),
            ], columns=["player_id", "split_value", *METRICS])
            controls_down = down[down.player_id.isin([GIBBS, JEFFERSON])]
            controls_comparison = compare(controls_down, expected_down, ["player_id", "split_value"])
            report["controls"]["reviewed_down_buckets"] = controls_comparison
            checks.append(("reviewed down controls", controls_comparison))
            report["controls"]["down_rows"] = json.loads(controls_down.to_json(orient="records"))
        if year == 2004:
            gap_observed = year_report["totals"]["targets"] < year_report["totals"]["receptions"]
            report["controls"]["historical_target_gap_persists"] = gap_observed
            if not gap_observed:
                report["failures"].append("2004 historical target-gap control unexpectedly changed")
        if database is not None:
            with duckdb.connect(str(database), read_only=True) as conn:
                stored = conn.execute("""
                    SELECT player_id, split_value, att AS targets, cmp AS receptions,
                           yards AS receiving_yards, td AS receiving_tds
                    FROM player_splits WHERE season=? AND category='receiving' AND split_dim='down'
                """, [year]).df()
            # Compare only players already stored: this is not a new admission policy.
            comparable = down[down.player_id.isin(stored.player_id)]
            year_report["existing_stored_players"] = int(stored.player_id.nunique())
            year_report["upstream_vs_existing_splits"] = compare(comparable, stored, ["player_id", "split_value"])
        report["seasons"][str(year)] = year_report
    for name, comparison in checks:
        for metric, values in comparison.items():
            if values["mismatches"]:
                report["failures"].append(f"{name}: {metric} ({values['mismatches']})")
    report["timings"] = load(output / "timings.csv").to_dict(orient="records")
    report["input_sha256"] = {}
    for path in sorted(output.glob("*.rds")):
        with path.open("rb") as source:
            report["input_sha256"][path.name] = hashlib.file_digest(source, "sha256").hexdigest()
    report["passed"] = not report["failures"]
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--database", type=Path)
    args = parser.parse_args()
    report = evaluate(args.output, args.database)
    path = args.output / "evaluation.json"
    path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"passed": report["passed"], "failures": report["failures"],
                      "report": str(path), "season_totals": {
                          year: data["totals"] for year, data in report["seasons"].items()}}, indent=2))
    if not report["passed"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
